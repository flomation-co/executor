func Execute(flow *core.Flow, node *core.Node, inputs []*core.Connection) (map[string]interface{}, error) {
	auth, client, errResult := cg.Client(inputs)
	if errResult != nil {
		return errResult, nil
	}
	problemID, err := cg.RequiredString("problem_ocid", inputs)
	if err != nil {
		return cg.ErrorResult(err.Error()), nil
	}

	resp, err := client.GetProblem(cg.Context(), cloudguard.GetProblemRequest{ProblemId: &problemID})
	if err != nil {
		return cg.ErrorResult(auth.OCIError(err)), nil
	}
	problem := cg.SummariseProblem(&resp.Problem)
	return cg.Result(fmt.Sprintf("Problem %q (%s, risk %s)", problem["id"], problem["lifecycle_state"], problem["risk_level"]), map[string]interface{}{
		"problem": problem, "id": problem["id"], "lifecycle_state": problem["lifecycle_state"],
	}), nil
}
