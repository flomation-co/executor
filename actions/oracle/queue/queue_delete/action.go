func Execute(flow *core.Flow, node *core.Node, inputs []*core.Connection) (map[string]interface{}, error) {
	queueID, err := q.RequiredString("queue_ocid", inputs)
	if err != nil {
		return q.ErrorResult(err.Error()), nil
	}
	auth, client, errResult := q.AdminClient(inputs)
	if errResult != nil {
		return errResult, nil
	}

	resp, err := client.DeleteQueue(q.Context(), queue.DeleteQueueRequest{QueueId: &queueID})
	if err != nil {
		return q.ErrorResult(auth.OCIError(err)), nil
	}
	return q.Result(fmt.Sprintf("Deleting queue %q — it will move to DELETING then DELETED", queueID), map[string]interface{}{
		"id":              queueID,
		"work_request_id": q.Str(resp.OpcWorkRequestId),
	}), nil
}
