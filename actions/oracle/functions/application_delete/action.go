func Execute(flow *core.Flow, node *core.Node, inputs []*core.Connection) (map[string]interface{}, error) {
	applicationID, err := fn.RequiredString("application_ocid", inputs)
	if err != nil {
		return fn.ErrorResult(err.Error()), nil
	}
	auth, client, errResult := fn.MgmtClient(inputs)
	if errResult != nil {
		return errResult, nil
	}

	_, err = client.DeleteApplication(fn.Context(), functions.DeleteApplicationRequest{ApplicationId: &applicationID})
	if err != nil {
		return fn.ErrorResult(auth.OCIError(err)), nil
	}
	return fn.Result(fmt.Sprintf("Deleted application %s", applicationID), map[string]interface{}{
		"id": applicationID,
	}), nil
}
