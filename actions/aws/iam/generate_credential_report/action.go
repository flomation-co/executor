var Outputs = [...]core.Connection{
	{Name: "tool_result", Type: core.ConnectionTypeString, Label: "Result summary"},
	{Name: "state", Type: core.ConnectionTypeString, Label: "State"},
	{Name: "description", Type: core.ConnectionTypeString, Label: "Description"},
}

func Execute(flow *core.Flow, node *core.Node, inputs []*core.Connection) (map[string]interface{}, error) {
	ctx := context.Background()

	cfg, err := awscommon.ConfigFromInputs(ctx, inputs)
	if err != nil {
		return nil, err
	}
	client := iam.NewFromConfig(cfg)

	out, err := client.GenerateCredentialReport(ctx, &iam.GenerateCredentialReportInput{})
	if err != nil {
		return nil, err
	}

	state := string(out.State)
	description := aws.ToString(out.Description)
	return map[string]interface{}{
		"tool_result": fmt.Sprintf("Credential report generation: %s", state),
		"state":       state,
		"description": description,
	}, nil
}
