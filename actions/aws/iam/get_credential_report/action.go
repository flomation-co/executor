var Outputs = [...]core.Connection{
	{Name: "tool_result", Type: core.ConnectionTypeString, Label: "Result summary"},
	{Name: "report_csv", Type: core.ConnectionTypeString, Label: "Report (CSV)"},
	{Name: "generated_time", Type: core.ConnectionTypeString, Label: "Generated Time"},
}

func Execute(flow *core.Flow, node *core.Node, inputs []*core.Connection) (map[string]interface{}, error) {
	ctx := context.Background()

	cfg, err := awscommon.ConfigFromInputs(ctx, inputs)
	if err != nil {
		return nil, err
	}
	client := iam.NewFromConfig(cfg)

	out, err := client.GetCredentialReport(ctx, &iam.GetCredentialReportInput{})
	if err != nil {
		return nil, err
	}

	// The SDK already base64-decodes the report body into out.Content, so it is
	// the plain CSV text of the report.
	reportCSV := string(out.Content)
	var generated string
	if out.GeneratedTime != nil {
		generated = out.GeneratedTime.Format(time.RFC3339)
	}
	return map[string]interface{}{
		"tool_result":    fmt.Sprintf("Retrieved credential report (%d bytes)", len(reportCSV)),
		"report_csv":     reportCSV,
		"generated_time": generated,
	}, nil
}
